#!/usr/bin/env python3
"""Generate Kotlin (kotlinx.serialization) types from the JSON Schema files in schema/.

Supports the subset the schema files use: objects (with allOf of $ref + inline object),
string enums, open enums (plain String), arrays, $ref across the two files, and the scalar
types string, integer, number, boolean. Anything else stops the run, so a schema change that
the generator cannot express is noticed instead of silently dropped.

    python3 tools/gen_kotlin.py            # rewrite generated/kotlin/src/main/kotlin/...
    python3 tools/gen_kotlin.py --check    # fail if the output would change
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMAS = {"Ocpi": ROOT / "schema" / "ocpi.schema.json", "Events": ROOT / "schema" / "events.schema.json"}
OUT_DIR = ROOT / "generated" / "kotlin" / "src" / "main" / "kotlin" / "com" / "evpnc" / "ocpimodel"
PACKAGE = "com.evpnc.ocpimodel"
KEYWORDS = {
    "as", "break", "class", "continue", "do", "else", "false", "for", "fun", "if", "in", "interface",
    "is", "null", "object", "package", "return", "super", "this", "throw", "true", "try", "typealias",
    "typeof", "val", "var", "when", "while",
}
HEADER = f"""// Generated by tools/gen_kotlin.py from schema/*.json. Do not edit.
@file:Suppress("unused", "ktlint")

package {PACKAGE}

import kotlinx.serialization.SerialName
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.JsonObject
"""


def camel(name: str) -> str:
    parts = name.split("_")
    out = parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])
    return f"`{out}`" if out in KEYWORDS else out


def enum_const(value: str) -> str:
    const = re.sub(r"\W", "_", value).upper()
    return f"V_{const}" if const[0].isdigit() else const


class Gen:
    def __init__(self) -> None:
        self.defs: dict[str, dict] = {}  # name -> schema
        self.file_of: dict[str, str] = {}
        for stem, path in SCHEMAS.items():
            for name, schema in json.loads(path.read_text())["$defs"].items():
                if name in self.defs:
                    sys.exit(f"definition {name} appears in two schema files")
                self.defs[name] = schema
                self.file_of[name] = stem

    def ref_name(self, ref: str) -> str:
        return ref.rsplit("/", 1)[-1]

    def flatten(self, schema: dict) -> dict:
        """Merge allOf members into one object schema."""
        if "allOf" not in schema:
            return schema
        merged = {"type": "object", "properties": {}, "required": []}
        for part in schema["allOf"]:
            if "$ref" in part:
                part = self.flatten(self.defs[self.ref_name(part["$ref"])])
            merged["properties"].update(part.get("properties", {}))
            merged["required"].extend(part.get("required", []))
        merged["title"] = schema.get("title")
        return merged

    def ktype(self, prop: dict, where: str) -> str:
        if "$ref" in prop:
            name = self.ref_name(prop["$ref"])
            if name not in self.defs:
                sys.exit(f"{where}: unresolved $ref {prop['$ref']}")
            return name
        t = prop.get("type")
        if "const" in prop:
            return "String"
        if t == "string":
            return "String"
        if t == "integer":
            return "Int"
        if t == "number":
            return "Double"
        if t == "boolean":
            return "Boolean"
        if t == "array":
            return f"List<{self.ktype(prop['items'], where)}>"
        sys.exit(f"{where}: unsupported schema {prop}")

    def emit(self, name: str) -> str:
        schema = self.defs[name]
        if "enum" in schema:
            lines = ["@Serializable", f"enum class {name}(val wire: String) {{"]
            consts = []
            for v in schema["enum"]:
                consts.append(f'    @SerialName("{v}") {enum_const(v)}("{v}")')
            lines.append(",\n".join(consts) + ";")
            lines.append("}")
            return "\n".join(lines)
        if schema.get("type") == "string":
            return f"/** Open string set: known values are listed in the schema, others are allowed. */\ntypealias {name} = String"
        if name == "Extensions":
            return "typealias Extensions = Map<String, JsonObject>"
        schema = self.flatten(schema)
        if schema.get("type") != "object":
            sys.exit(f"{name}: unsupported definition")
        required = set(schema.get("required", []))
        fields = []
        for prop, p in schema["properties"].items():
            kt = self.ktype(p, f"{name}.{prop}")
            kname = camel(prop)
            opt = prop not in required
            if "const" in p:
                ann = f'    @SerialName("{prop}") val {kname}: String = "{p["const"]}"'
            else:
                ann = f'    @SerialName("{prop}") val {kname}: {kt}{"? = null" if opt else ""}'
            fields.append(ann)
        # required fields first so positional construction stays stable
        fields.sort(key=lambda f: ("= null" in f) + 2 * (': String = "' in f))
        body = ",\n".join(fields)
        return f"@Serializable\ndata class {name}(\n{body},\n)"

    def render(self, stem: str) -> str:
        names = sorted(n for n, f in self.file_of.items() if f == stem)
        # EventEnvelope is only the base for the concrete events
        names = [n for n in names if n != "EventEnvelope"]
        return HEADER + "\n" + "\n\n".join(self.emit(n) for n in names) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    g = Gen()
    bad = 0
    for stem in SCHEMAS:
        dest = OUT_DIR / f"{stem}.kt"
        text = g.render(stem)
        if args.check:
            if not dest.exists() or dest.read_text() != text:
                print(f"{dest.relative_to(ROOT)} is out of date; run tools/gen_kotlin.py", file=sys.stderr)
                bad = 1
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(text)
            print(f"wrote {dest.relative_to(ROOT)}")
    return bad


if __name__ == "__main__":
    sys.exit(main())
